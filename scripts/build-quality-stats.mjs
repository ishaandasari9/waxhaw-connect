/**
 * Counts what the project actually verifies and writes src/qualityStats.js, so
 * the About page can state a test count without anyone remembering to update a
 * number. Run it after adding tests:  npm run stats
 *
 * The accessibility figure comes from the axe-core scan described in the
 * README; pass it in when a new audit is run:
 *   node scripts/build-quality-stats.mjs --violations 0
 */
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const SRC = fileURLToPath(new URL('../src', import.meta.url))
const OUTPUT = fileURLToPath(new URL('../src/qualityStats.js', import.meta.url))

export function countTests(source) {
  return (source.match(/^\s*it\(/gm) || []).length
}

const args = process.argv.slice(2)
const violationsFlag = args.indexOf('--violations')
const violations = violationsFlag >= 0 ? Number(args[violationsFlag + 1]) : 0

const files = (await readdir(SRC)).filter((name) => name.endsWith('.test.js'))
let tests = 0
for (const file of files) tests += countTests(await readFile(`${SRC}/${file}`, 'utf8'))

const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/New_York' }).format(new Date())
await writeFile(OUTPUT, `/**
 * Generated by \`npm run stats\`. Do not edit by hand.
 */
export const QUALITY_STATS = {
  tests: ${tests},
  testFiles: ${files.length},
  accessibilityViolations: ${violations},
  auditedOn: '${today}',
}
`)
console.log(`Wrote ${tests} tests across ${files.length} files, ${violations} accessibility violations.`)
